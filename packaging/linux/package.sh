#!/usr/bin/env bash
# Build the Linux release assets: a tarball, a .deb, a .rpm and an Arch package (.pkg.tar.zst).
#
# Usage: packaging/linux/package.sh <version> <path-to-ted-binary> <out-dir> [arch]
#
# <version> is the bare version (0.1.0 or 0.1.0-rc.1, no leading "v").
# [arch] is x86_64 (default) or aarch64.
# Requires nfpm (https://nfpm.goreleaser.com), bsdtar (libarchive) and zstd on PATH.
set -euo pipefail

if [[ $# -lt 3 || $# -gt 4 ]]; then
    echo "usage: $0 <version> <ted-binary> <out-dir> [x86_64|aarch64]" >&2
    exit 2
fi

version=$1
binary=$2
out_dir=$3
arch=${4:-x86_64}

case "$arch" in
x86_64) deb_arch=amd64 ;;
aarch64) deb_arch=arm64 ;;
*)
    echo "error: unsupported arch '$arch' (use x86_64 or aarch64)" >&2
    exit 2
    ;;
esac

if ! command -v nfpm >/dev/null 2>&1; then
    echo "error: nfpm not found on PATH, install it from https://nfpm.goreleaser.com" >&2
    exit 1
fi
for tool in bsdtar zstd; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "error: $tool not found on PATH (packages libarchive-tools and zstd on Debian)" >&2
        exit 1
    fi
done
if [[ ! -f $binary ]]; then
    echo "error: binary not found: $binary" >&2
    exit 1
fi

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
linux_dir=$root/packaging/linux
icons_dir=$root/packaging/icons
mkdir -p "$out_dir"
out_dir=$(cd "$out_dir" && pwd)
binary=$(cd "$(dirname "$binary")" && pwd)/$(basename "$binary")

app_id=codes.tanis.ted
sizes=(16 24 32 48 64 128 256 512)

# 1. Tarball with a /usr-like prefix layout.
name=ted-$version-linux-$arch
stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT
top=$stage/$name
install -Dm755 "$binary" "$top/bin/ted"
install -Dm644 "$linux_dir/$app_id.desktop" "$top/share/applications/$app_id.desktop"
install -Dm644 "$icons_dir/ted.svg" \
    "$top/share/icons/hicolor/scalable/apps/$app_id.svg"
for size in "${sizes[@]}"; do
    install -Dm644 "$icons_dir/png/ted-$size.png" \
        "$top/share/icons/hicolor/${size}x${size}/apps/$app_id.png"
done
install -m644 "$root/LICENSE" "$top/LICENSE"
install -m644 "$root/NOTICE" "$top/NOTICE"
install -m644 "$root/README.md" "$top/README.md"
tar --sort=name --owner=0 --group=0 --numeric-owner --mtime='UTC 2020-01-01' \
    -C "$stage" -czf "$out_dir/$name.tar.gz" "$name"

# 2. deb and rpm with nfpm.
export TED_VERSION=$version
export TED_ARCH=$deb_arch
export TED_BIN=$binary
export TED_ROOT=$root
# The file names use <version> as given: nfpm's default names carry the "~" of a pre-release
# (0.1.0~rc.1), which GitHub turns into "." on upload, breaking SHA256SUMS. The version inside the
# packages keeps the "~", so a pre-release still sorts before the final release.
nfpm pkg --config "$linux_dir/nfpm.yaml" --packager deb \
    --target "$out_dir/ted_${version}_$deb_arch.deb"
nfpm pkg --config "$linux_dir/nfpm.yaml" --packager rpm \
    --target "$out_dir/ted-$version-1.$arch.rpm"

# 3. Arch package, written directly: nfpm's archlinux packager has no optdepends (Vulkan must
# stay optional) and drops the pre-release from pkgver. A pacman package is a zstd tarball of the
# files plus .PKGINFO and .MTREE, as makepkg writes them, with the dependencies of the deb. pkgver has no dash: 0.1.0-rc.1 becomes 0.1.0rc.1, which pacman sorts
# before 0.1.0. The file name keeps the dash, like the deb and the rpm.
pkg=$stage/arch
install -Dm755 "$top/bin/ted" "$pkg/usr/bin/ted"
cp -R "$top/share" "$pkg/usr/share"
install -Dm644 "$root/LICENSE" "$pkg/usr/share/licenses/ted/LICENSE"
install -Dm644 "$root/NOTICE" "$pkg/usr/share/licenses/ted/NOTICE"
{
    echo "# Generated by packaging/linux/package.sh"
    echo "pkgname = ted"
    echo "pkgbase = ted"
    echo "pkgver = ${version//-/}-1"
    echo "pkgdesc = A fast, lightweight text editor"
    echo "url = https://github.com/tanisperez/ted"
    echo "builddate = ${SOURCE_DATE_EPOCH:-$(date +%s)}"
    echo "packager = Estanislao Pérez Nartallo <tanisperez@gmail.com>"
    echo "size = $(du -sb --apparent-size "$pkg/usr" | cut -f1)"
    echo "arch = $arch"
    echo "license = Apache-2.0"
    for dep in libxkbcommon libxkbcommon-x11 libxcb wayland libglvnd; do
        echo "depend = $dep"
    done
    echo "optdepend = vulkan-icd-loader: Vulkan renderer"
} >"$pkg/.PKGINFO"
owner=(--uid 0 --gid 0 --uname root --gname root)
(
    cd "$pkg"
    LANG=C bsdtar "${owner[@]}" -czf .MTREE --format=mtree \
        --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' .PKGINFO usr
    LANG=C bsdtar "${owner[@]}" -cf - .MTREE .PKGINFO usr |
        zstd -q -19 -T0 -o "$out_dir/ted-$version-1-$arch.pkg.tar.zst"
)

echo "Built in $out_dir:"
ls -1 "$out_dir"
